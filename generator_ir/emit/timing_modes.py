"""Timing harness mode implementations.

Split from host_harness.py. Each function emits the launch+timing code for
one mode (simple / CI / clock64 / loop / profiler) onto a SourceWriter.
"""

from __future__ import annotations

from generator_ir.emit.base_emitter import SourceWriter

def harness_simple_mode(w, api, launch: str) -> None:
    """5 warmup launches + 10 event-timed launches; print avg_time_ms."""
    w, api, check = w, api, api.error_check_call
    w.line("// Warmup")
    w.line("for (int w = 0; w < 5; w++) {")
    w.kx_indent()
    w.line(f"{launch};")
    w.kx_dedent()
    w.line("}")
    w.line(f"{check}({api.get_last_error}());")
    w.line(f"{check}({api.device_sync}());")
    w.blank()
    w.line(f"{check}({api.memset}(d_output, 0, buf_size * sizeof(unsigned int)));")
    w.blank()
    w.line("// Timed runs")
    w.line(f"{api.event_t} start, stop;")
    w.line(f"{check}({api.event_create}(&start));")
    w.line(f"{check}({api.event_create}(&stop));")
    w.line("const int RUNS = 10;")
    w.line("float total_ms = 0.0f;")
    w.line("for (int r = 0; r < RUNS; r++) {")
    w.kx_indent()
    w.line(f"{check}({api.memset}(d_output, 0, buf_size * sizeof(unsigned int)));")
    w.line(f"{check}({api.event_record}(start));")
    w.line(f"{launch};")
    w.line(f"{check}({api.event_record}(stop));")
    w.line(f"{check}({api.get_last_error}());")
    w.line(f"{check}({api.event_sync}(stop));")
    w.line("float ms = 0.0f;")
    w.line(f"{check}({api.event_elapsed}(&ms, start, stop));")
    w.line("total_ms += ms;")
    w.kx_dedent()
    w.line("}")
    w.line('printf("avg_time_ms=%.3f\\n", total_ms / RUNS);')

